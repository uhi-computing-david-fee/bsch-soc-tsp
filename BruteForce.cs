namespace TspStarter;

public static class BruteForce
{
    // Enumerate all orderings after the fixed start, but evaluate each symmetric tour once.
    // 'out' lets the method return a route AND report the number of tours evaluated.
    public static int[] Solve(double[,] distances, int startCity, out long toursEvaluated)
    {
        int cityCount = distances.GetLength(0);
        if (cityCount < 2 || distances.GetLength(1) != cityCount)
            throw new ArgumentException("Distances must be a square matrix with at least two cities.");
        if (startCity < 0 || startCity >= cityCount)
            throw new ArgumentException("Starting city is out of range.");
        if (cityCount > 10)
            throw new ArgumentException("Brute force is limited to 10 cities. Use heuristics for larger experiments.");

        for (int i = 0; i < cityCount; i++)
            for (int j = 0; j < cityCount; j++)
            {
                if (!double.IsFinite(distances[i, j]) || distances[i, j] < 0)
                    throw new ArgumentException("Distances must be finite and non-negative.");
                if (distances[i, j] != distances[j, i])
                    throw new ArgumentException("This solver removes reverse duplicates and requires symmetric distances.");
            }

        int[] route = new int[cityCount];
        route[0] = startCity;
        int position = 1;
        for (int city = 0; city < cityCount; city++)
            if (city != startCity) route[position++] = city;

        int[] bestRoute = new int[cityCount];
        double bestCost = double.PositiveInfinity;
        long count = 0;

        // This local function can use route, bestRoute, bestCost and count above.
        void Search(int nextPosition)
        {
            if (nextPosition == cityCount)
            {
                // A tour and its reverse have the same cost for symmetric TSP.
                // Keep the orientation whose second city ID is smaller than its last.
                // This removes one of each reverse pair for ANY fixed starting city.
                // With two cities there is just one ordering, so keep that special case.
                if (cityCount > 2 && route[1] > route[cityCount - 1]) return;

                // Count only the tours whose costs are actually calculated.
                // All (n-1)! permutations are still generated by the recursion.
                double cost = Tsp.RouteCost(distances, route);
                count++;
                if (!double.IsFinite(cost)) throw new ArgumentException("The total route cost is too large.");
                if (cost < bestCost)
                {
                    bestCost = cost;
                    bestRoute = (int[])route.Clone(); // Preserve it before route changes again.
                }
                return;
            }

            for (int i = nextPosition; i < cityCount; i++)
            {
                // Choose a city for this position, explore the remaining positions,
                // then undo the swap so the next choice starts from the same state.
                (route[nextPosition], route[i]) = (route[i], route[nextPosition]);
                Search(nextPosition + 1);
                (route[nextPosition], route[i]) = (route[i], route[nextPosition]);
            }
        }

        Search(1); // For n >= 3: (n-1)! permutations generated, (n-1)! / 2 tours evaluated.
        toursEvaluated = count;
        return bestRoute;
    }
}
